# if permite ejecutar un bloque de código solamente cuando una condición es verdadera

edad = 20

if edad >= 18:
    print("Es mayor de edad")

# else permite ejecutar una alternativa cuando la condición del if es falsa
else:
    print("No es mayor de edad")


