# Ejercicio 2: Crea una matriz de 0 con una magnitud de 3X3

# 1. Definición de la matriz como estructura de datos (lista de listas 3x3)
matriz = [
    [0, 0, 0],
    [0, 0, 0],
    [0, 0, 0]
]

print("Matriz de 3x3 (Estructura de listas):")
for fila in matriz:
    print(fila)

# 2. Representación en formato de texto (string) utilizando tabulación (\t) y salto de línea (\n)
# Basado en lo aprendido en la clase de tipos de datos para formar tablas
matriz_str = "0\t0\t0\n0\t0\t0\n0\t0\t0"

print("\nMatriz de 3x3 (Formato String con \\t y \\n):")
print(matriz_str)
